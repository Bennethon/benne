/**
 * Reads the generated handle modules (`src/game/game.ids.ts`, `rooms/<id>/<id>.ids.ts`, …; see
 * docs/bennescript-ergonomics-refactor.md §7 and decision 23) so editor tooling can map handle
 * names to content IDs and back without re-implementing the generator's naming rules.
 *
 * Every handle in those modules is built from its content ID (`new HotspotHandle("club",
 * "club-hotspot-battery")`), or is an alias of another handle (`export const room = rooms.club`).
 * This module evaluates those declarations into a small tree of {@link IdsNode}s.
 *
 * Pure apart from the injected `readFile`; no `vscode` import (the TS server plugin uses it).
 */
import * as path from 'node:path';
import type * as TS from 'typescript';

export type ContentRef =
    | { kind: 'room'; id: string }
    | { kind: 'prop' | 'hotspot' | 'point' | 'region' | 'walkable'; roomId: string; id: string }
    | { kind: 'character'; roomId: string | null; id: string }
    | { kind: 'item'; id: string }
    | { kind: 'dialog'; id: string }
    | { kind: 'dialogOption'; dialogId: string; id: string }
    | { kind: 'gui'; id: string }
    | { kind: 'guiControl'; guiId: string; id: string }
    | { kind: 'sfx' | 'music' | 'video'; id: string }
    | { kind: 'verb'; id: string }
    | { kind: 'fallbacks' };

export interface IdsNode {
    ref?: ContentRef;
    members: Map<string, IdsValue>;
}

/** `rooms.club` in a module that imports `rooms`, or a local `const` of the module. */
interface IdsAlias {
    alias: { root: string; path: string[] };
}

type IdsValue = IdsNode | IdsAlias;

export interface VerbInfo {
    id: string;
    label: string;
    usesItem: boolean;
    /** `onTalkTo` */
    method: string;
    /** `onUseItem`, for `usesItem` verbs */
    itemMethod: string | null;
}

interface ParsedIdsModule {
    text: string;
    imports: Map<string, { module: string; name: string }>;
    /** Top-level `const`s, exported or not. */
    locals: Map<string, IdsValue>;
    exports: Set<string>;
    verbs: VerbInfo[];
}

/** First line of every generated module (scripts/lib/generateGameHandles.mjs). */
export const GENERATED_IDS_MARKER = '// AUTO-GENERATED by scripts/generate-game-ids.mjs';

const HANDLE_CLASSES: Record<string, (args: string[]) => ContentRef | undefined> = {
    RoomHandle: ([id]) => (id !== undefined ? { kind: 'room', id } : undefined),
    PropHandle: ([roomId, id]) => (roomId !== undefined && id !== undefined ? { kind: 'prop', roomId, id } : undefined),
    HotspotHandle: ([roomId, id]) => (roomId !== undefined && id !== undefined ? { kind: 'hotspot', roomId, id } : undefined),
    PointHandle: ([roomId, id]) => (roomId !== undefined && id !== undefined ? { kind: 'point', roomId, id } : undefined),
    RegionHandle: ([roomId, id]) => (roomId !== undefined && id !== undefined ? { kind: 'region', roomId, id } : undefined),
    WalkableHandle: ([roomId, id]) =>
        roomId !== undefined && id !== undefined ? { kind: 'walkable', roomId, id } : undefined,
    ItemHandle: ([id]) => (id !== undefined ? { kind: 'item', id } : undefined),
    DialogHandle: ([id]) => (id !== undefined ? { kind: 'dialog', id } : undefined),
    GuiHandle: ([id]) => (id !== undefined ? { kind: 'gui', id } : undefined),
    SfxHandle: ([id]) => (id !== undefined ? { kind: 'sfx', id } : undefined),
    MusicHandle: ([id]) => (id !== undefined ? { kind: 'music', id } : undefined),
    VideoHandle: ([id]) => (id !== undefined ? { kind: 'video', id } : undefined),
};

export function sameContent(a: ContentRef, b: ContentRef, opts?: { anyCharacterRoom?: boolean }): boolean {
    if (a.kind !== b.kind) {
        return false;
    }
    if (a.kind === 'fallbacks') {
        return true;
    }
    const x = a as Record<string, unknown>;
    const y = b as Record<string, unknown>;
    if (x.id !== y.id) {
        return false;
    }
    if (a.kind === 'character') {
        return opts?.anyCharacterRoom === true || x.roomId === y.roomId;
    }
    return x.roomId === y.roomId && x.dialogId === y.dialogId && x.guiId === y.guiId;
}

/** `rusty-bucket` → `rustyBucket`, `AI problem` → `aiProblem` (mirrors `camelCaseId` in scripts/lib/benneNames.mjs). */
export function camelCaseId(id: string): string {
    const parts = String(id).split(/[^A-Za-z0-9]+/).filter(Boolean);
    if (parts.length === 0) {
        return '';
    }
    const [first, ...rest] = parts;
    const head = /^[A-Z0-9]+$/.test(first) ? first.toLowerCase() : first[0].toLowerCase() + first.slice(1);
    return head + rest.map((p) => p[0].toUpperCase() + p.slice(1)).join('');
}

/** `talkTo` → `TalkTo` (mirrors `pascalCaseId` in scripts/lib/benneNames.mjs). */
export function pascalCaseId(id: string): string {
    return String(id)
        .split(/[^A-Za-z0-9]+/)
        .filter(Boolean)
        .map((p) => p[0].toUpperCase() + p.slice(1))
        .join('');
}

/** Script file → its generated sibling module: `rooms/club/club.room.ts` → `rooms/club/club.ids.ts`. */
export function siblingIdsModulePath(scriptFile: string): string | undefined {
    const m = /^(.*[/\\])([^/\\]+)\.(room|character|dialog|gui)\.ts$/.exec(scriptFile);
    return m ? `${m[1]}${m[2]}.ids.ts` : undefined;
}

export class IdsIndex {
    private readonly modules = new Map<string, ParsedIdsModule | null>();
    private readonly ts: typeof TS;
    /** Absolute path of `src/game`. */
    readonly gameRoot: string;
    private readonly readFile: (absPath: string) => string | undefined;

    constructor(ts: typeof TS, gameRoot: string, readFile: (absPath: string) => string | undefined) {
        this.ts = ts;
        this.gameRoot = gameRoot;
        this.readFile = readFile;
    }

    get gameModulePath(): string {
        return path.join(this.gameRoot, 'game.ids.ts');
    }

    /** `@game` and relative `.ids` specifiers → absolute module path. */
    resolveSpecifier(fromFile: string, specifier: string): string | undefined {
        if (specifier === '@game') {
            return this.gameModulePath;
        }
        if (!specifier.startsWith('.')) {
            return undefined;
        }
        const resolved = path.resolve(path.dirname(fromFile), specifier);
        if (/\.ids\.ts$/.test(resolved)) {
            return resolved;
        }
        if (/\.ids$/.test(resolved)) {
            return `${resolved}.ts`;
        }
        if (path.resolve(resolved) === path.resolve(this.gameRoot, 'game.ids')) {
            return this.gameModulePath;
        }
        return undefined;
    }

    /** Resolves `name.path…` exported by `modulePath`. */
    resolveExport(modulePath: string, name: string, memberPath: readonly string[] = []): IdsNode | undefined {
        return this.resolveIn(modulePath, name, memberPath, 0);
    }

    /** Resolves an import of a script (`import { items } from '@game'` + `['soda']`). */
    resolveImport(
        scriptFile: string,
        specifier: string,
        importedName: string,
        memberPath: readonly string[],
    ): IdsNode | undefined {
        const modulePath = this.resolveSpecifier(scriptFile, specifier);
        return modulePath ? this.resolveExport(modulePath, importedName, memberPath) : undefined;
    }

    /** The configured verbs, as the generator saw them (`verbSpecs` in `game.ids.ts`). */
    verbs(): VerbInfo[] {
        return this.module(this.gameModulePath)?.verbs ?? [];
    }

    verb(verbId: string): VerbInfo {
        const found = this.verbs().find((v) => v.id === verbId);
        if (found) {
            return found;
        }
        const pascal = pascalCaseId(verbId);
        return { id: verbId, label: verbId, usesItem: false, method: `on${pascal}`, itemMethod: null };
    }

    /** Whether `modulePath` exists (has been generated). */
    hasModule(modulePath: string): boolean {
        return this.module(modulePath) !== undefined;
    }

    /**
     * How a script refers to `ref`: a flat export of its sibling `.ids` module (`battery`,
     * `regions.leave`, `options.bye`, `room`, a character script's own `jensen`) when it has one,
     * else a path into `@game` (`items.soda`, `characters.jensen`, `dialogs.driver.options.wrench`).
     * A room's flat character is room-scoped, so it never stands in for `characters.x`.
     */
    findBinding(scriptFile: string, ref: ContentRef): { module: string; name: string; expr: string } | undefined {
        const candidates: Array<{ spec: string; modulePath: string }> = [];
        const sibling = siblingIdsModulePath(scriptFile);
        if (sibling) {
            candidates.push({ spec: `./${path.basename(sibling, '.ts')}`, modulePath: sibling });
        }
        candidates.push({ spec: '@game', modulePath: this.gameModulePath });
        for (const { spec, modulePath } of candidates) {
            const mod = this.module(modulePath);
            if (!mod) {
                continue;
            }
            // The shortest path wins: `options.bye` over `dialog.options.bye`.
            let best: { name: string; path: string[] } | undefined;
            for (const name of mod.exports) {
                const found = this.searchNode(modulePath, name, ref, 3);
                if (found && (!best || found.length < best.path.length)) {
                    best = { name, path: found };
                }
            }
            if (best) {
                return { module: spec, name: best.name, expr: [best.name, ...best.path].join('.') };
            }
        }
        return undefined;
    }

    /** Every export of a module with its resolved node (for completions and tests). */
    exportsOf(modulePath: string): Map<string, IdsNode> {
        const out = new Map<string, IdsNode>();
        const mod = this.module(modulePath);
        if (!mod) {
            return out;
        }
        for (const name of mod.exports) {
            const node = this.resolveExport(modulePath, name);
            if (node) {
                out.set(name, node);
            }
        }
        return out;
    }

    /** Each room's generated module, with its key in `rooms` (`rooms.club` → `club`). */
    roomModules(): Array<{ roomId: string; key: string; modulePath: string }> {
        const out: Array<{ roomId: string; key: string; modulePath: string }> = [];
        const rooms = this.resolveExport(this.gameModulePath, 'rooms');
        for (const key of rooms?.members.keys() ?? []) {
            const ref = this.resolveExport(this.gameModulePath, 'rooms', [key])?.ref;
            if (ref?.kind !== 'room') {
                continue;
            }
            const modulePath = path.join(this.gameRoot, 'rooms', ref.id, `${ref.id}.ids.ts`);
            if (this.hasModule(modulePath)) {
                out.push({ roomId: ref.id, key, modulePath });
            }
        }
        return out;
    }

    /**
     * The content behind a declaration in a generated module: the `const` or object property at
     * `position` (for go-to-definition from a handle to its JSON).
     */
    refAtDeclaration(modulePath: string, sourceFile: TS.SourceFile, position: number): ContentRef | undefined {
        const ts = this.ts;
        let node: TS.Node | undefined = findInnermostNode(ts, sourceFile, position);
        const names: string[] = [];
        while (node) {
            if (ts.isPropertyAssignment(node) && (ts.isIdentifier(node.name) || ts.isStringLiteral(node.name))) {
                names.unshift(node.name.text);
            } else if (
                ts.isObjectLiteralExpression(node) &&
                ts.isNewExpression(node.parent) &&
                node.parent.arguments?.[1] === node &&
                ts.isIdentifier(node.parent.expression)
            ) {
                // `new DialogHandle("barista", { bye: "bye" })` is `dialogs.barista.options.bye`.
                const className = node.parent.expression.text;
                if (className === 'DialogHandle' || className === 'GuiHandle') {
                    names.unshift(className === 'DialogHandle' ? 'options' : 'controls');
                }
            } else if (ts.isVariableDeclaration(node) && ts.isIdentifier(node.name)) {
                if (!ts.isVariableStatement(node.parent.parent) || node.parent.parent.parent !== sourceFile) {
                    return undefined;
                }
                const resolved = this.resolveIn(modulePath, node.name.text, names, 0);
                return resolved?.ref;
            }
            node = node.parent;
        }
        return undefined;
    }

    // ─── internals ───────────────────────────────────────────────────────────

    private searchNode(modulePath: string, name: string, ref: ContentRef, depth: number): string[] | undefined {
        const root = this.resolveExport(modulePath, name);
        if (!root) {
            return undefined;
        }
        const visit = (node: IdsNode, at: string[], left: number): string[] | undefined => {
            if (node.ref && sameContent(node.ref, ref)) {
                return at;
            }
            if (left === 0) {
                return undefined;
            }
            for (const key of node.members.keys()) {
                const child = this.resolveMember(modulePath, node, key);
                if (child) {
                    const hit = visit(child, [...at, key], left - 1);
                    if (hit) {
                        return hit;
                    }
                }
            }
            return undefined;
        };
        return visit(root, [], depth);
    }

    private resolveIn(modulePath: string, name: string, memberPath: readonly string[], hops: number): IdsNode | undefined {
        if (hops > 8) {
            return undefined;
        }
        const mod = this.module(modulePath);
        if (!mod) {
            return undefined;
        }
        const local = mod.locals.get(name);
        let node: IdsNode | undefined;
        if (local) {
            node = this.deref(modulePath, local, hops);
        } else {
            const imported = mod.imports.get(name);
            if (!imported) {
                return undefined;
            }
            const target = this.resolveSpecifier(modulePath, imported.module);
            node = target ? this.resolveIn(target, imported.name, [], hops + 1) : undefined;
        }
        for (const key of memberPath) {
            if (!node) {
                return undefined;
            }
            node = this.resolveMember(modulePath, node, key, hops);
        }
        return node;
    }

    private resolveMember(modulePath: string, node: IdsNode, key: string, hops = 0): IdsNode | undefined {
        const child = node.members.get(key);
        return child ? this.deref(modulePath, child, hops) : undefined;
    }

    private deref(modulePath: string, value: IdsValue, hops: number): IdsNode | undefined {
        if ('alias' in value) {
            return this.resolveIn(modulePath, value.alias.root, value.alias.path, hops + 1);
        }
        return value;
    }

    private module(modulePath: string): ParsedIdsModule | undefined {
        const key = path.resolve(modulePath);
        const text = this.readFile(key);
        const cached = this.modules.get(key);
        if (text === undefined) {
            this.modules.set(key, null);
            return undefined;
        }
        if (cached && cached.text === text) {
            return cached;
        }
        const parsed = parseIdsModule(this.ts, key, text);
        this.modules.set(key, parsed);
        return parsed;
    }
}

function findInnermostNode(ts: typeof TS, sourceFile: TS.SourceFile, position: number): TS.Node | undefined {
    let found: TS.Node | undefined;
    const visit = (node: TS.Node): void => {
        if (position >= node.getStart(sourceFile) && position < node.getEnd()) {
            found = node;
            ts.forEachChild(node, visit);
        }
    };
    ts.forEachChild(sourceFile, visit);
    return found;
}

function stringArgs(ts: typeof TS, args: readonly TS.Expression[]): string[] {
    const out: string[] = [];
    for (const arg of args) {
        if (ts.isStringLiteral(arg) || ts.isNoSubstitutionTemplateLiteral(arg)) {
            out.push(arg.text);
        } else if (arg.kind === ts.SyntaxKind.NullKeyword) {
            out.push('\u0000null');
        } else {
            break;
        }
    }
    return out;
}

function unwrapExpression(ts: typeof TS, expr: TS.Expression): TS.Expression {
    let e = expr;
    while (
        ts.isParenthesizedExpression(e) ||
        ts.isNonNullExpression(e) ||
        ts.isAsExpression(e) ||
        ts.isSatisfiesExpression(e)
    ) {
        e = e.expression;
    }
    return e;
}

/** `a.b.c` → `{ root: 'a', path: ['b', 'c'] }`. */
export function expressionPath(ts: typeof TS, expr: TS.Expression): { root: string; path: string[] } | undefined {
    const e = unwrapExpression(ts, expr);
    if (ts.isIdentifier(e)) {
        return { root: e.text, path: [] };
    }
    if (ts.isPropertyAccessExpression(e) && ts.isIdentifier(e.name)) {
        const base = expressionPath(ts, e.expression);
        return base ? { root: base.root, path: [...base.path, e.name.text] } : undefined;
    }
    return undefined;
}

function parseIdsModule(ts: typeof TS, fileName: string, text: string): ParsedIdsModule {
    const sf = ts.createSourceFile(fileName, text, ts.ScriptTarget.Latest, true, ts.ScriptKind.TS);
    const imports = new Map<string, { module: string; name: string }>();
    const locals = new Map<string, IdsValue>();
    const exports = new Set<string>();
    let verbSpecs: TS.ArrayLiteralExpression | undefined;

    for (const stmt of sf.statements) {
        if (ts.isImportDeclaration(stmt) && ts.isStringLiteral(stmt.moduleSpecifier)) {
            const bindings = stmt.importClause?.namedBindings;
            if (bindings && ts.isNamedImports(bindings)) {
                for (const el of bindings.elements) {
                    imports.set(el.name.text, {
                        module: stmt.moduleSpecifier.text,
                        name: (el.propertyName ?? el.name).text,
                    });
                }
            }
            continue;
        }
        if (!ts.isVariableStatement(stmt)) {
            continue;
        }
        const exported = stmt.modifiers?.some((m) => m.kind === ts.SyntaxKind.ExportKeyword) === true;
        for (const decl of stmt.declarationList.declarations) {
            if (!ts.isIdentifier(decl.name) || !decl.initializer) {
                continue;
            }
            if (decl.name.text === 'verbSpecs' && ts.isArrayLiteralExpression(unwrapExpression(ts, decl.initializer))) {
                verbSpecs = unwrapExpression(ts, decl.initializer) as TS.ArrayLiteralExpression;
            }
            if (exported) {
                exports.add(decl.name.text);
            }
        }
    }

    const verbs = verbSpecs ? parseVerbSpecs(ts, verbSpecs) : [];

    const evaluate = (expr: TS.Expression): IdsValue | undefined => {
        const e = unwrapExpression(ts, expr);
        if (ts.isNewExpression(e) && ts.isIdentifier(e.expression)) {
            const args = [...(e.arguments ?? [])];
            const className = e.expression.text;
            if (className === 'VerbHandle') {
                const arg = args[0] ? unwrapExpression(ts, args[0]) : undefined;
                if (arg && ts.isElementAccessExpression(arg) && ts.isNumericLiteral(arg.argumentExpression)) {
                    const verb = verbs[Number(arg.argumentExpression.text)];
                    return { ref: verb ? { kind: 'verb', id: verb.id } : undefined, members: new Map() };
                }
                return { members: new Map() };
            }
            if (className === 'FallbacksHandle') {
                return { ref: { kind: 'fallbacks' }, members: new Map() };
            }
            if (className === 'CharacterHandle') {
                const [roomId, id] = stringArgs(ts, args);
                if (id === undefined) {
                    return { members: new Map() };
                }
                return {
                    ref: { kind: 'character', roomId: roomId === '\u0000null' ? null : (roomId ?? null), id },
                    members: new Map(),
                };
            }
            const make = HANDLE_CLASSES[className];
            const ref = make ? make(stringArgs(ts, args)) : undefined;
            const members = new Map<string, IdsValue>();
            if (ref && (ref.kind === 'dialog' || ref.kind === 'gui')) {
                const map = args[1] ? unwrapExpression(ts, args[1]) : undefined;
                const children = new Map<string, IdsValue>();
                if (map && ts.isObjectLiteralExpression(map)) {
                    for (const prop of map.properties) {
                        if (
                            ts.isPropertyAssignment(prop) &&
                            (ts.isIdentifier(prop.name) || ts.isStringLiteral(prop.name)) &&
                            ts.isStringLiteral(prop.initializer)
                        ) {
                            children.set(prop.name.text, {
                                ref:
                                    ref.kind === 'dialog'
                                        ? { kind: 'dialogOption', dialogId: ref.id, id: prop.initializer.text }
                                        : { kind: 'guiControl', guiId: ref.id, id: prop.initializer.text },
                                members: new Map(),
                            });
                        }
                    }
                }
                members.set(ref.kind === 'dialog' ? 'options' : 'controls', { members: children });
            }
            return { ref, members };
        }
        if (ts.isCallExpression(e)) {
            // `__withVerbs(new PropHandle(…))`, `withMusicControls({ … })`, `withVerbMethods(new FallbacksHandle(), …)`
            for (const arg of e.arguments) {
                const inner = unwrapExpression(ts, arg);
                if (ts.isNewExpression(inner) || ts.isObjectLiteralExpression(inner) || ts.isCallExpression(inner)) {
                    return evaluate(inner);
                }
            }
            return undefined;
        }
        if (ts.isObjectLiteralExpression(e)) {
            const members = new Map<string, IdsValue>();
            for (const prop of e.properties) {
                if (ts.isPropertyAssignment(prop) && (ts.isIdentifier(prop.name) || ts.isStringLiteral(prop.name))) {
                    const value = evaluate(prop.initializer);
                    if (value) {
                        members.set(prop.name.text, value);
                    }
                }
            }
            return { members };
        }
        const p = expressionPath(ts, e);
        return p ? { alias: p } : undefined;
    };

    for (const stmt of sf.statements) {
        if (!ts.isVariableStatement(stmt)) {
            continue;
        }
        for (const decl of stmt.declarationList.declarations) {
            if (ts.isIdentifier(decl.name) && decl.initializer) {
                const value = evaluate(decl.initializer);
                if (value) {
                    locals.set(decl.name.text, value);
                }
            }
        }
    }

    return { text, imports, locals, exports, verbs };
}

function parseVerbSpecs(ts: typeof TS, list: TS.ArrayLiteralExpression): VerbInfo[] {
    const out: VerbInfo[] = [];
    for (const el of list.elements) {
        if (!ts.isObjectLiteralExpression(el)) {
            continue;
        }
        const fields: Record<string, string | boolean | null> = {};
        for (const prop of el.properties) {
            if (!ts.isPropertyAssignment(prop) || !ts.isIdentifier(prop.name)) {
                continue;
            }
            const v = prop.initializer;
            if (ts.isStringLiteral(v)) {
                fields[prop.name.text] = v.text;
            } else if (v.kind === ts.SyntaxKind.TrueKeyword) {
                fields[prop.name.text] = true;
            } else if (v.kind === ts.SyntaxKind.FalseKeyword) {
                fields[prop.name.text] = false;
            } else if (v.kind === ts.SyntaxKind.NullKeyword) {
                fields[prop.name.text] = null;
            }
        }
        if (typeof fields.id !== 'string') {
            continue;
        }
        const pascal = pascalCaseId(fields.id);
        out.push({
            id: fields.id,
            label: typeof fields.label === 'string' ? fields.label : fields.id,
            usesItem: fields.usesItem === true,
            method: typeof fields.method === 'string' ? fields.method : `on${pascal}`,
            itemMethod: typeof fields.itemMethod === 'string' ? fields.itemMethod : null,
        });
    }
    return out;
}
