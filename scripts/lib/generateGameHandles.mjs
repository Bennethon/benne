function emitRoomModule(m, roomName, characterAnimations) {
  const id = m.room.id;
  const runtime = new Set();
  const game = new Set([`rooms`]);
  if (m.props.length) runtime.add('PropHandle');
  if (m.hotspots.length) runtime.add('HotspotHandle');
  if (m.characters.length) runtime.add('CharacterHandle');
  if (m.points.length) runtime.add('PointHandle');
  if (m.regions.length) runtime.add('RegionHandle');
  if (m.walkables.length) runtime.add('WalkableHandle');
  if (m.props.length || m.hotspots.length || m.characters.length) {
    game.add('__withVerbs');
    game.add('type VerbId');
  }
  let out = header(
    `Handles for room "${id}" (${m.room.file}): \`room\`, its props, hotspots and characters, plus\n * \`points\`, \`regions\` and \`walkables\` (docs/bennescript-ergonomics-refactor.md §7).`,
  );
  out += importLine(runtime, '@benne/script');
  out += importLine(game, '@game');
  if (m.props.length) out += `\n/** Animation tags on this room's Aseprite sheet. */\ntype PropAnimation = ${m.propAnimation};\n`;
  out += `\nexport const room = rooms.${roomName};\n`;
  const section = (title, rows, make) => {
    if (!rows.length) return '';
    return `\n// ${title}\n${rows.map((r) => `${doc(`\`${r.id}\``)}\nexport const ${r.name} = ${make(r)};`).join('\n')}\n`;
  };
  out += section('Props', m.props, (p) => `__withVerbs(new PropHandle<VerbId, PropAnimation>(${str(id)}, ${str(p.id)}))`);
  out += section('Hotspots', m.hotspots, (h) => `__withVerbs(new HotspotHandle<VerbId>(${str(id)}, ${str(h.id)}))`);
  out += section(
    'Characters',
    m.characters,
    (c) => `__withVerbs(new CharacterHandle<VerbId, ${characterAnimations.get(c.id)}>(${str(id)}, ${str(c.id)}))`,
  );
  out += `\nexport const points = ${objectLiteral(m.points, (p) => `new PointHandle(${str(id)}, ${str(p.id)})`)};\n`;
  out += `\nexport const regions = ${objectLiteral(m.regions, (r) => `new RegionHandle(${str(id)}, ${str(r.id)})`)};\n`;
  out += `\nexport const walkables = ${objectLiteral(m.walkables, (w) => `new WalkableHandle(${str(id)}, ${str(w.id)})`)};\n`;
  return out;
}

function emitCharacterModule(m, characterName) {
  const id = m.character.id;
  return (
    header(
      `Handle for character "${id}" (${m.character.file}): \`${m.name}\`, the same object as \`characters.${characterName}\`.\n * Its handlers apply wherever the character is (docs/bennescript-ergonomics-refactor.md §4.9).`,
    ) + `import { characters } from '@game';\n\nexport const ${m.name} = characters.${characterName};\n`
  );
}

function emitDialogModule(d, dialogName) {
  return (
    header(`Handles for dialog "${d.id}" (${d.file}): \`dialog\` and its \`options\` (docs/bennescript-ergonomics-refactor.md §4.8).`) +
    `import { dialogs } from '@game';\n\nexport const dialog = dialogs.${dialogName};\nexport const options = dialog.options;\n`
  );
}

function emitGuiModule(g, guiName, controls) {
  let out =
    header(`Handles for GUI "${g.id}" (${g.file}): \`gui\` and its controls (docs/bennescript-ergonomics-refactor.md §4.15).`) +
    `import { guis } from '@game';\n\nexport const gui = guis.${guiName};\n`;
  if (controls.length) {
    out += `\n${controls.map((c) => `${doc(`${c.type ? `${c.type} ` : ''}\`${c.id}\``)}\nexport const ${c.name} = gui.controls.${c.name};`).join('\n')}\n`;
  }
  return out;
}
